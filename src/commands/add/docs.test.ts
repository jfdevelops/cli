import { describe, expect, it } from 'vitest';
import { createDocsWorkflow, createIgnoreEdit, createReadmeEdit, createScriptsEdit } from './docs.js';

describe('docs addon files', () => {
  it('watches the documented package and uses the project package manager', () => {
    const workflow = createDocsWorkflow('npm', 'packages/core');

    expect(workflow).toContain("      - 'packages/core/src/**'\n      - 'packages/core/package.json'\n      - 'packages/core/CHANGELOG.md'");
    expect(workflow).toContain('          cache: npm\n      - run: npm ci\n      - run: npm run docs:generate\n      - run: npm run docs:check');
    expect(workflow).not.toContain('pnpm/action-setup');
  });

  it('sets up Bun without Node.js', () => {
    const workflow = createDocsWorkflow('bun', '.');

    expect(workflow).toContain('      - uses: oven-sh/setup-bun@v2\n      - run: bun install --frozen-lockfile');
    expect(workflow).not.toContain('setup-node');
  });

  it('adds missing scripts and keeps existing ones', () => {
    const manifest = JSON.parse(createScriptsEdit().transform('{"name":"lib","scripts":{"build":"tsc","docs:generate":"mine"}}')) as { scripts: Record<string, string> };

    expect(manifest.scripts).toEqual({ 'docs:generate': 'mine', 'docs:check': 'jfdevelops-docs check', build: 'tsc' });
  });

  it('adds the ignore entries once', () => {
    const edit = createIgnoreEdit();
    const once = edit.transform('dist/');

    expect(once).toBe('dist/\n\n# Generated by @jfdevelops/docs\ndocs/docs.json\ndocs/**/meta.json\n');
    expect(edit.transform(once)).toBe(once);
    expect(edit.transform(undefined)).toBe('# Generated by @jfdevelops/docs\ndocs/docs.json\ndocs/**/meta.json\n');
  });

  it('starts docs/README.md only when it is missing', () => {
    const edit = createReadmeEdit();

    expect(edit.transform('# Mine\n')).toBe('# Mine\n');
    expect(edit.transform(undefined)).toContain('docs:generate');
  });
});
