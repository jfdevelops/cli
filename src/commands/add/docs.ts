import { join, posix } from 'node:path';
import type { PackageManagerName } from '../../detect/package-manager.js';
import { readPackageManifest } from '../../detect/manifest.js';
import type { DesiredFile, FileEdit } from '../../plan/create.js';
import type { Prompter } from '../../prompts/prompter.js';
import type { ProjectAdditions } from './additions.js';

export const docsAddonName = 'docs';
export const docsPackage = '@jfdevelops/docs';
export const docsWorkflowPath = '.github/workflows/docs.yml';

const docsOwner = { type: 'addon' as const, name: docsAddonName };
const ignoreMarker = '# Generated by @jfdevelops/docs';
const ignoreLines = [ignoreMarker, 'docs/docs.json', 'docs/**/meta.json'];
export const docsScripts = { 'docs:generate': 'jfdevelops-docs generate', 'docs:check': 'jfdevelops-docs check' };

const docsReadme = `# Documentation

Pages live under \`framework/<framework>/v<major>/\`, one directory per documented major.
Each page is Markdown with \`title\`, \`description\` and \`order\` frontmatter.

\`docs.json\`, every \`meta.json\` and the current major's \`reference/\` are generated by
\`@jfdevelops/docs\` and are not committed:

\`\`\`sh
docs:generate   # API reference, docs.json and meta.json
docs:check      # frontmatter, layout, links, anchors and install commands
\`\`\`
`;

function titleFromPackageName(name: string) {

  return (name.split('/').at(-1) ?? name)
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

// Yarn 2 and later use --immutable; Yarn 1, and a project without a packageManager field, use --frozen-lockfile.
function isModernYarn(packageManagerField: string | undefined) {
  const major = Number(packageManagerField?.match(/^yarn@(\d+)\./)?.[1] ?? 1);

  return major >= 2;
}

// Commands for CI; each installs exactly what the lockfile records.
function describeCommands(packageManager: PackageManagerName, packageManagerField: string | undefined) {
  switch (packageManager) {
    case 'npm':

      return { install: 'npm ci', run: 'npm run' };
    case 'pnpm':

      return { install: 'pnpm install --frozen-lockfile', run: 'pnpm run' };
    case 'yarn':

      return { install: isModernYarn(packageManagerField) ? 'yarn install --immutable' : 'yarn install --frozen-lockfile', run: 'yarn run' };
    case 'bun':

      return { install: 'bun install --frozen-lockfile', run: 'bun run' };
  }
}

function describeSetupSteps(packageManager: PackageManagerName) {
  if (packageManager === 'bun') {

    return ['      - uses: oven-sh/setup-bun@v2'];
  }

  return [
    ...(packageManager === 'pnpm' ? ['      - uses: pnpm/action-setup@v6'] : []),
    // Runners ship Yarn 1; Corepack provides the version in packageManager before setup-node reads its cache.
    ...(packageManager === 'yarn' ? ['      - run: corepack enable'] : []),
    '      - uses: actions/setup-node@v7',
    '        with:',
    '          node-version: 24',
    `          cache: ${packageManager}`,
  ];
}

// The paths whose changes can change the generated docs: the pages, the documented package, and the setup.
function describeWatchedPaths(packageDirectory: string) {
  const inPackage = (file: string) => (packageDirectory === '.' ? file : posix.join(packageDirectory, file));

  return ['docs/**', inPackage('src/**'), inPackage('package.json'), inPackage('CHANGELOG.md'), 'jfdevelops.json', docsWorkflowPath];
}

/**
 * A workflow that generates and checks the docs, only when a change can affect them. packageManagerField
 * is the root package.json packageManager value, which selects the Yarn install flags.
 */
export function createDocsWorkflow(packageManager: PackageManagerName, packageDirectory: string, packageManagerField?: string) {
  const { install, run } = describeCommands(packageManager, packageManagerField);
  const paths = describeWatchedPaths(packageDirectory).map((path) => `      - '${path}'`);

  return [
    'name: Docs',
    '',
    'on:',
    '  pull_request:',
    '    paths:',
    ...paths,
    '  push:',
    '    branches: [main]',
    '    paths:',
    ...paths,
    '',
    'permissions:',
    '  contents: read',
    '',
    'concurrency:',
    '  group: docs-${{ github.ref }}',
    "  cancel-in-progress: ${{ github.event_name == 'pull_request' }}",
    '',
    'jobs:',
    '  docs:',
    '    name: Generate and check docs',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 15',
    '    steps:',
    '      - uses: actions/checkout@v7',
    ...describeSetupSteps(packageManager),
    `      - run: ${install}`,
    `      - run: ${run} docs:generate`,
    `      - run: ${run} docs:check`,
    '',
  ].join('\n');
}

// Adds the docs scripts that are missing; an existing script with the same name is kept.
export function createScriptsEdit(): FileEdit {

  return {
    path: 'package.json',
    transform: (current) => {
      const manifest = JSON.parse(current ?? '{}') as { scripts?: Record<string, string> };

      manifest.scripts = { ...docsScripts, ...manifest.scripts };

      return `${JSON.stringify(manifest, null, 2)}\n`;
    },
  };
}

export function createIgnoreEdit(): FileEdit {

  return {
    path: '.gitignore',
    transform: (current) => {
      if (current?.includes(ignoreMarker)) {

        return current;
      }

      const existing = current === undefined || current === '' ? '' : `${current.replace(/\n*$/, '')}\n\n`;

      return `${existing}${ignoreLines.join('\n')}\n`;
    },
  };
}

// A docs addon recorded without its package, by init adoption or a setup that failed, still needs setting up.
export function isDocsSetUp(options: Record<string, unknown>) {

  return typeof options['package'] === 'string';
}

// Starts docs/README.md only when the project has none.
export function createReadmeEdit(): FileEdit {

  return { path: 'docs/README.md', transform: (current) => current ?? docsReadme };
}

/**
 * Asks which package the docs describe and the library name, then returns the addon options and the
 * workflow, scripts, ignore entries and docs README to add.
 */
export async function createDocsSetup(additions: ProjectAdditions, prompter: Prompter) {
  const { project, config } = additions;
  const candidates = [...new Set([...config.targets.filter((target) => target.kind === 'library').map((target) => target.path), '.'])];
  const packageDirectory =
    candidates.length === 1
      ? '.'
      : await prompter.select({
          message: 'Which package do the docs describe?',
          choices: candidates.map((candidate) => ({ value: candidate, label: candidate === '.' ? 'the project root' : candidate })),
          initialValue: candidates[0] ?? '.',
        });
  const manifest = await readPackageManifest(join(project.root, packageDirectory));

  if (!manifest?.name) {
    throw new Error(`${packageDirectory === '.' ? 'The project root' : packageDirectory} has no package.json with a name.`);
  }

  const name = await prompter.text({ message: 'Library name shown in the docs', defaultValue: titleFromPackageName(manifest.name) });
  const rootManifest = await readPackageManifest(project.root);
  const workflow = createDocsWorkflow(config.project.packageManager, packageDirectory, rootManifest?.packageManager);
  const files: DesiredFile[] = [{ path: docsWorkflowPath, owner: docsOwner, content: workflow }];

  return {
    options: { package: packageDirectory, name },
    files,
    edits: [createScriptsEdit(), createIgnoreEdit(), createReadmeEdit()],
  };
}
